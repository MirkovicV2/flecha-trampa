import type { ArrowDesign, ArrowLayer, ExitStyle, Point } from './arrow-designs';
import type { SkinId } from './collection';

type NewSkin = Exclude<
  SkinId,
  'classic' | 'chevron' | 'vector' | 'pixel' | 'prism' | 'orbit' | 'royal' | 'nova'
>;
const plate = (
  points: readonly Point[],
  fill: ArrowLayer['fill'] = 'body',
  opacity = 1,
): ArrowLayer => ({ points, fill, opacity });
const seam = (
  points: readonly Point[],
  stroke: ArrowLayer['stroke'] = 'edge',
  width = 1.7,
): ArrowLayer => ({ points, stroke, width, opacity: 0.85 });

const signatures: Record<ExitStyle, string> = {
  precision: 'Corte de aire · línea de luz',
  echo: 'Doble onda · impulso paralelo',
  electric: 'Arco de tensión · ramificaciones',
  pixel: 'Disolución digital · pasos de ocho bits',
  prism: 'Fractura mineral · facetas en expansión',
  orbit: 'Anillos orbitales · rotación elíptica',
  crown: 'Sello dorado · lluvia de metal',
  nova: 'Ignición triple · plasma',
  frost: 'Cristalización · agujas de hielo',
  flame: 'Combustión · brasas ascendentes',
  ink: 'Corte de tinta · trazos diagonales',
  glitch: 'Desfase digital · bandas discontinuas',
  petal: 'Floración · pétalos en espiral',
  sonar: 'Eco abisal · ondas concéntricas',
  meteor: 'Impacto estelar · meteoros cruzados',
  ribbon: 'Aurora · cintas ondulantes',
};

function die(
  serial: number,
  workshop: string,
  finish: string,
  description: string,
  exit: ExitStyle,
  body: readonly Point[],
  detail: readonly Point[],
  extra: readonly ArrowLayer[] = [],
  baseColor?: number,
): ArrowDesign {
  return {
    serial: `FT—${String(serial).padStart(3, '0')}`,
    workshop,
    finish,
    description,
    exit,
    effect: signatures[exit],
    ...(baseColor === undefined ? {} : { baseColor, paletteAccent: true }),
    layers: [
      plate(body),
      plate(detail, baseColor === undefined ? 'edge' : 'accent', 0.8),
      ...extra,
    ],
  };
}

